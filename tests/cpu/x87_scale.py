"""Compare native and translated FSCALE of the x87 leaf-function profile.

Usage:
    python tests/cpu/x87_scale.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_scale.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_scale.py check <harness> <native> <lifted> [controls...]

CTest runs the check-* parts as separate cases in parallel; `check` runs every part serially for a direct run.

The exports, harness and guards follow tests/cpu/x87_add.py, and the other steps use the format of
tests/cpu/x87_moves.py. emit checks that every decoded x87 instruction is the form its sequence names.
The model scales with Fraction arithmetic and is independent of tools/x87_soft.h.
"""
from fractions import Fraction
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_integers as integers  # noqa: E402
import x87_xtract as xtract  # noqa: E402
from x87_add import INDEFINITE, J, Q, classify, from_binary, m80_bytes, round_format, to_binary  # noqa: E402
from x87_div import SIZE  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT

# ("fscale",) is the new step; ("fxtract",) is the step of tests/cpu/x87_xtract.py, and the others use
# the x87_moves and x87_integers formats. FSCALE scales ST(0) by ST(1) and keeps both on the stack, so
# each export stores ST(1) too.
SEQUENCES = {
    "scale_m80": ("pair80", [("fld", "m80", 16), ("fld", "m80", 0), ("fscale",), ("fstp", "m80", 0),
                             ("fstp", "m80", 16)]),
    "scale_to_m64": ("pair80", [("fld", "m80", 16), ("fld", "m80", 0), ("fscale",), ("fstp", "m64", 0),
                                ("fstp", "m80", 16)]),
    "scale_to_m32": ("pair80", [("fld", "m80", 16), ("fld", "m80", 0), ("fscale",), ("fstp", "m32", 0),
                                ("fstp", "m80", 16)]),
    "scale_f64": ("pair64", [("fld", "m64", 8), ("fld", "m64", 0), ("fscale",), ("fstp", "m80", 0),
                             ("fstp", "m80", 16)]),
    # An integer scale from FILD, and two scalings in a row.
    "scale_by_i32": ("m80i32", [("fild", "i32", 16), ("fld", "m80", 0), ("fscale",), ("fstp", "m80", 0),
                                ("fistp", "i32", 16)]),
    "scale_twice": ("pair80", [("fld", "m80", 16), ("fld", "m80", 0), ("fscale",), ("fscale",), ("fstp", "m80", 0),
                               ("fstp", "m80", 16)]),
    # FXTRACT then FSCALE rebuilds the value; the exponent is popped by FSTP m80.
    "xtract_scale": ("m80", [("fld", "m80", 0), ("fxtract",), ("fscale",), ("fstp", "m80", 0), ("fstp", "m80", 16)]),
    # The eighth register, then every value back out.
    "scale_depth8": ("m64x8", [("fld", "m64", 8 * k) for k in range(8)] + [("fscale",)]
                     + [("fstp", "m64", 8 * k) for k in range(8)]),
}

CONTROLS = {
    # The result rounds to 53 significand bits, as if the precision control applied.
    "pc53": (re.compile(r"x87_scale_format\{64, "), "x87_scale_format{53, "),
    # A result below the normal range rounds toward zero.
    "chop": (re.compile(r"x87_scale_format, x87_rounding\(cw\)\);  // scale round"), "x87_scale_format, 3);  // scale round"),
    # A negative non-integer scale rounds toward negative infinity instead of toward zero.
    "floor": (re.compile(r"n = x87_sign\(b\) \? -magnitude : magnitude;  // scale truncate"),
              "n = x87_sign(b) ? -magnitude - (y.e < 63 && (y.e < 0 || (y.sig << (y.e + 1)) != 0)) : magnitude;"
              "  // scale truncate"),
    # ST(1) = -inf gives +0 whatever the sign of ST(0).
    "neginf": (re.compile(r"x87_is_inf\(a\) \? x87_indefinite : X87Value\{0, s\};"),
               "x87_is_inf(a) ? x87_indefinite : X87Value{0, 0};"),
    # A zero scaled by +inf stays zero instead of giving the indefinite.
    "zeroinf": (re.compile(r"return x87_is_zero\(a\) \? x87_indefinite : "), "return x87_is_zero(a) ? a : "),
    # The operands are exchanged: ST(1) scaled by ST(0).
    "swap": (re.compile(r"x87_scale\(x87_slot\[(\d)\], x87_slot\[(\d)\], x87_cw\)"),
             r"x87_scale(x87_slot[\2], x87_slot[\1], x87_cw)"),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    return f"    {step[0]}" if step[0] in ("fscale", "fxtract") else integers.asm_line(step)


def expected_form(step):
    return (step[0], "") if step[0] in ("fscale", "fxtract") else integers.expected_form(step)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_scale",
             "; Generated by tests/cpu/x87_scale.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for FSCALE in the x87 leaf-function profile. Each export",
             "; reads an input block at RCX, writes an output block at RDX and returns with the x87 stack empty.",
             ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [integers.decoded_form(i) for i in body if is_x87(i)]
            wanted = [expected_form(s) for s in steps]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

LIMIT = 1 << 17  # a scale beyond this over- or underflows every finite value, so the model clamps to it


def nan_pick(a, b):
    """The NaN result of two operands (Intel SDM Vol. 1, Table 4-7, x87 column, as measured in x87_add)."""
    na, nb = classify(a)[0] == "nan", classify(b)[0] == "nan"
    if na and nb:
        qa, qb = bool(a[0] & Q), bool(b[0] & Q)
        pick = (a if qa else b) if qa != qb else (b if (b[0], -(b[1] >> 15)) > (a[0], -(a[1] >> 15)) else a)
    else:
        pick = a if na else b
    return pick[0] | Q, pick[1]


def scale(a, b):
    """FSCALE with control word 0x027F: ST(0) = a scaled by 2^trunc(ST(1) = b)."""
    ca, cb = classify(a), classify(b)
    if "unsupported" in (ca[0], cb[0]):
        return INDEFINITE
    if "nan" in (ca[0], cb[0]):
        return nan_pick(a, b)
    sign = a[1] & 0x8000
    if cb[0] == "inf":
        if cb[1]:
            return INDEFINITE if ca[0] == "inf" else (0, sign)
        return INDEFINITE if ca[0] == "zero" else (J, sign | 0x7FFF)
    if ca[0] in ("zero", "inf"):
        return a
    n = 0 if cb[0] == "zero" else min(int(cb[2]), LIMIT)  # int() truncates the Fraction toward zero
    n = -n if cb[1] else n
    rounded = round_format(ca[2] * Fraction(2) ** n, 64, 16383, 0x7FFE)
    if rounded is None:
        return J, sign | 0x7FFF
    m, biased = rounded
    return m, sign | biased


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op == "fscale":
            slots[-1] = scale(slots[-1], slots[-2])
        elif op == "fxtract":
            exponent, significand = xtract.xtract(slots[-1])
            slots[-1] = exponent
            slots.append(significand)
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        elif op == "fild":
            slots.append(integers.from_integer(read("m32", args[1]) - ((read("m32", args[1]) >> 31) << 32)))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        else:  # ("fistp", "i32", offset)
            bits = integers.to_integer(slots.pop(), 32, False)
            out[args[1]:args[1] + 4] = bits.to_bytes(4, "little")
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def m80_value(q):
    """The m80 encoding of a nonzero Fraction that fits in 64 significand bits."""
    return base.m80_exact(int(q < 0), abs(q))


def scales(rng):
    """ST(1) values: integers, non-integers of both signs, tiny, huge and denormal values."""
    values = [(0, 0), (0, 0x8000)]
    for n in list(range(-70, 71)) + [-16382, -16383, -16445, -16446, -16447, -16500, 16383, 16384, 32767, -32768,
                                     -32769, 65536, -65536, 1 << 30, -(1 << 30)]:
        if n:
            values.append(m80_value(Fraction(n)))
    for q in (Fraction(1, 2), Fraction(3, 2), Fraction(255, 128), Fraction(5, 2), Fraction(1, 1 << 40),
              Fraction((1 << 62) - 1, 1 << 61), Fraction(70001, 2)):  # non-integers, each with both signs
        values += [m80_value(q), m80_value(-q)]
    values += [(1, 0), (J - 1, 0x8000), (J, 0x3FFF + 70), (J, 0xBFFF + 70), (J, 0x7FFE), (J, 0xFFFE),
               (J | 1, 0x3FFF + 63), (J | 1, 0xBFFF + 63), (J | 1, 0x3FFF + 62)]
    for _ in range(40):
        values.append((J | rng.getrandbits(63), rng.randint(0x3FFF - 4, 0x3FFF + 14) | rng.choice((0, 0x8000))))
    return values


def operands(rng):
    """ST(0) values: the m80 singles of x87_add, values near the normal-range boundary with tie and
    sticky patterns in their low bits, denormals and pseudo-denormals, and random values."""
    values = list(base.m80_singles())
    for low in (0, 1, 0x400, 0x401, 0x7FF, 0x800, (1 << 32) | 1, (1 << 63) - 1):
        values += [(J | low, 0x3FFF), (J | low, 0xBFFF), (J | low, 0x3FFF + 100), (J | low, 1)]
    for _ in range(60):
        values.append((J | rng.getrandbits(63), rng.randint(1, 0x7FFE) | rng.choice((0, 0x8000))))
        values.append((rng.getrandbits(rng.randint(1, 64)) or 1, rng.choice((0, 0x8000))))
    return values


def cases():
    rng = random.Random(97)
    specials = base.special_m80()
    st1, st0 = scales(rng), operands(rng)
    pairs = [(a, b) for a in specials for b in specials]
    pairs += [(a, b) for a in st0[::3] for b in st1[::4]]
    # Results that land in the denormal range at a rounding tie, just above or below it, and at the
    # boundaries to zero and to the normal range.
    for low in (1 << 10, 3 << 10, (1 << 10) + 1, 1, 0x7FF, 0xFFF):
        for k in range(0, 66, 5):
            for sign in (0, 0x8000):
                a = (J | low, 0x3FFF | sign)
                pairs.append((a, m80_value(Fraction(-(16382 + k)))))
    for _ in range(300):
        pairs.append((rng.choice(st0), rng.choice(st1)))
    f64 = base.f64_bits()
    ints = [0, 1, -1, 2, -2, 63, -63, 64, -64, 1000, -1000, 16383, -16383, 16445, -16446, 70000, -70000,
            (1 << 31) - 1, -(1 << 31)]
    blocks = {
        "pair80": [m80_bytes(a) + m80_bytes(b) for a, b in pairs],
        "pair64": [a.to_bytes(8, "little") + b.to_bytes(8, "little") for a in f64[::2] for b in f64[::2]],
        "m80i32": [m80_bytes(a)[:16] + (n & 0xFFFFFFFF).to_bytes(4, "little") for a in st0[::4] for n in ints],
        "m80": [m80_bytes(v) for v in st0] + [m80_bytes(v) for v in specials],
        "m64x8": [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(8)) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def build_expected():
    return [(name, data, reference(name, data)) for name, data in cases()]


def check_target(label, harness_path, path, expected):
    """Every case, then the x87_call caller-state check, against one DLL (native or translated)."""
    run = base.Runner(harness_path, path)
    bad = 0
    for name, data, want in expected:
        got, state = run(name, data)
        if not base.entry_state_ok(state):
            raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                 "0x027f and an empty stack at TOP 0")
        if got != want:
            if bad < 3:
                print(f"{label} mismatch: {name}(input {data[:48].hex()})\n  got      {got[:48].hex()}\n"
                      f"  expected {want[:48].hex()}")
            bad += 1
    if bad:
        raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{label}: {len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the "
          "reference; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    run = base.Runner(harness_path, path)
    failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
    if failed:
        raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} {label} exports")


def check_controls(harness_path, expected, control_paths):
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")


def check(harness_path, native_path, lifted_path, *control_paths):
    expected = build_expected()
    check_target("native", harness_path, native_path, expected)
    check_target("lifted", harness_path, lifted_path, expected)
    check_controls(harness_path, expected, control_paths)
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fscale on an empty stack": (attempt("d9 fd c3"), "x87 stack underflow"),
        "fscale with one value": (attempt(f"{fld} d9 fd {fstp} c3"), "x87 stack underflow"),
        "fscale with one store": (attempt(f"{fld} {fld} d9 fd {fstp} c3"), "x87 stack not empty at return"),
        "fnsave": (attempt(f"{fld} {fld} dd 31 d9 fd {fstp} {fstp} c3"), "unsupported x87 operation"),
        "fxrstor": (attempt(f"0f ae 09 {fld} {fld} d9 fd {fstp} {fstp} c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, *args = sys.argv[1:]  # check-rejections takes no paths
    first, second = (args + [None, None])[:2]
    rest = args[2:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    elif mode == "check-rejections":  # no fixture needed
        check_rejections()
    elif mode == "check-native":  # args: harness, native DLL
        check_target("native", first, second, build_expected())
    elif mode == "check-lifted":  # args: harness, lifted DLL
        check_target("lifted", first, second, build_expected())
    elif mode == "check-controls":  # args: harness, unused, then the control DLLs
        check_controls(first, build_expected(), rest)
    else:
        raise ValueError(mode)
